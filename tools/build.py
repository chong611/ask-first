"""Generate agent entry files from the single source in src/.

dist/project/  committed into a repo (this is all a cloud session sees)
  AGENTS.md                                 core rules
  CLAUDE.md                                 "@AGENTS.md" (Claude Code reads only CLAUDE.md when both exist)
  .claude/skills/<name>/SKILL.md            pb-rehearse, pb-status, pb-handoff, lessons
  .claude/hooks/agent-playbook/*.py         hook scripts
  .claude/settings.fragment.json            hooks + ask rules, merged into settings.json by install.py
dist/global/   for ~/.claude on the owner's computer
  rules/agent-playbook.md                   core only; install.py appends the profiles you choose
  skills/..., agent-playbook/hooks/..., settings.fragment.json

A personal profile lives in ~/.claude/rules/owner.md, the user's own file (DECISIONS Q155).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"

PUBLIC_PROFILES = ("lang-zh-CN", "advisor")  # opt-in at install (Q156)
VERSION = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
CLIENTS = ("codex", "cursor", "gemini")  # other agents: src/hooks/client_<name>.py + tools/target_<name>.py
HOOK_FILES = ("playbook_hook.py", "policy.py", "report.py", "headings.py", "secret_patterns.py",
              *(f"client_{c}.py" for c in CLIENTS))
HEADER = "<!-- generated by tools/build.py from src/; do not edit -->\n"
MARKER = "agent-playbook"
GLOBAL_HOOK = "{HOME}/.claude/agent-playbook/hooks/playbook_hook.py"  # {HOME} and python filled in at install

# Content-scoped ask rules: a second layer under the PreToolUse hook (rule 2.3).
ASK_RULES = [
    "Bash(gh pr create *)", "Bash(gh pr merge *)", "Bash(gh repo create *)", "Bash(gh repo delete *)",
    "Bash(git push --force *)", "Bash(git push -f *)", "Bash(git reset --hard *)", "Bash(git clean *)",
    "Bash(npm publish *)", "Bash(crontab *)",
    "mcp__github__create_pull_request", "mcp__github__merge_pull_request",
]
# Windows sessions run commands through the PowerShell tool; same rules, same shape.
ASK_RULES += [r.replace("Bash(", "PowerShell(", 1) for r in ASK_RULES if r.startswith("Bash(")]


def read(path: Path) -> str:
    text = path.read_text(encoding="utf-8-sig")  # Windows PowerShell 5.1 saves files with a BOM
    return text if text.endswith("\n") else text + "\n"


def core() -> str:
    return read(SRC / "rules" / "core.md")


def profile(name: str) -> str:
    return read(SRC / "profiles" / f"{name}.md")


def settings_fragment(script: str, python: str = "python3") -> str:
    """Exec form (command + args): no shell, so paths and Windows need no quoting tricks."""
    def entry(matcher=None, block=False, timeout=10):
        hook = {"type": "command", "command": python, "args": [script], "timeout": timeout}
        if block:
            hook["onFailure"] = "block"  # a crashed policy hook must not let tier-2 through
        e = {"hooks": [hook]}
        if matcher is not None:
            e["matcher"] = matcher
        return [e]

    fragment = {
        "hooks": {
            "PreToolUse": entry("*", block=True),
            "PostToolUse": entry("^(Write|Edit|MultiEdit|NotebookEdit|Bash|PowerShell)$|^mcp__"),
            "UserPromptSubmit": entry(),
            "Stop": entry(timeout=15),
            "InstructionsLoaded": entry(),
            "SessionStart": entry("compact"),
        },
        "permissions": {"ask": ASK_RULES},
    }
    return json.dumps(fragment, indent=2, ensure_ascii=False) + "\n"


def skills() -> dict[str, str]:
    return {p.parent.name: read(p) for p in sorted((SRC / "skills").glob("*/SKILL.md"))}


def hooks() -> dict[str, str]:
    return {name: read(SRC / "hooks" / name) for name in HOOK_FILES}


def outputs() -> dict[str, str]:
    """Map dist-relative path -> file content."""
    out = {
        "project/AGENTS.md": HEADER + core(),
        "project/CLAUDE.md": HEADER + "@AGENTS.md\n",
        "project/.claude/settings.fragment.json": settings_fragment(
            "${CLAUDE_PROJECT_DIR}/.claude/hooks/agent-playbook/playbook_hook.py"),
        "global/rules/agent-playbook.md": HEADER + core(),
        "global/settings.fragment.json": settings_fragment(GLOBAL_HOOK, "{PYTHON}"),
    }
    for name, text in skills().items():
        out[f"project/.claude/skills/{name}/SKILL.md"] = text
        out[f"global/skills/{name}/SKILL.md"] = text
    for name, text in hooks().items():
        out[f"project/.claude/hooks/{MARKER}/{name}"] = text
        out[f"global/{MARKER}/hooks/{name}"] = text
    for client in CLIENTS:
        for rel, text in target(client).outputs(sys.modules[__name__]).items():
            if not rel.startswith(f"{client}/"):
                raise ValueError(f"target_{client} wrote outside dist/{client}/: {rel}")
            out[rel] = text
    return out


def target(client: str):
    import importlib
    sys.path.insert(0, str(ROOT / "tools"))
    return importlib.import_module(f"target_{client}")


def write(dist: Path = DIST) -> list[Path]:
    expected = outputs()
    written = []
    for rel, content in expected.items():
        path = dist / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    for path in dist.rglob("*"):  # drop files no longer generated
        if path.is_file() and path.relative_to(dist).as_posix() not in expected:
            path.unlink()
    return written


def stale(dist: Path = DIST) -> list[str]:
    """Return dist paths whose content differs from a fresh build, plus leftovers."""
    expected = outputs()
    bad = [rel for rel, content in expected.items()
           if not (dist / rel).exists() or (dist / rel).read_text(encoding="utf-8") != content]
    if dist.exists():
        bad += [p.relative_to(dist).as_posix() for p in dist.rglob("*")
                if p.is_file() and p.relative_to(dist).as_posix() not in expected]
    return bad


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if dist/ is stale")
    args = parser.parse_args(argv)
    if args.check:
        bad = stale()
        for rel in bad:
            print(f"stale: dist/{rel} (run python3 tools/build.py)", file=sys.stderr)
        return 1 if bad else 0
    print(f"wrote {len(write())} files under dist/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
