"""Install target for OpenAI Codex (python tools/install.py global --client codex).

What goes where (Codex docs, read 2026-10-28: learn.chatgpt.com/docs/hooks, /docs/agent-configuration/rules,
/docs/agent-configuration/agents-md, /docs/build-skills):
  ~/.codex/AGENTS.md                      the core and chosen profiles in a marked block; the user's own
                                          lines stay as they are (Codex reads only the first non-empty of
                                          AGENTS.override.md, AGENTS.md)
  ~/.codex/hooks.json                     merged: our handlers (they run .../agent-playbook/hooks/playbook_hook.py)
                                          are replaced, every other hook is kept
  ~/.codex/agent-playbook/hooks/*.py      the hook scripts
  ~/.codex/rules/agent-playbook.rules     our own execpolicy file (prefix rules that make Codex ask first);
                                          default.rules is never touched
  ~/.agents/skills/<name>/SKILL.md        the skills
  ~/.codex/config.toml                    one marked line, `unified_exec_tty = false` in [features]: no
                                          interactive terminals, so write_stdin cannot type commands that no
                                          hook sees. Every other byte stays; uninstall removes just that line
                                          (and the [features] header, if we added it).
auth.json is never touched; Codex itself records hook trust in config.toml.
"""

from __future__ import annotations

import json
import os
import re
import shlex
from pathlib import Path

HOOK_REL = "agent-playbook/hooks"  # under ~/.codex
RULES_NAME = "agent-playbook.rules"
CORE_END = "<!-- /agent-playbook:core -->"
# Codex fails a timed-out hook open (the call runs), so allow more than the policy's own 6 s limit plus git.
EVENTS = {
    "PreToolUse": ("*", 30),
    "PostToolUse": ("^(apply_patch|Bash)$|^mcp__", 15),
    "UserPromptSubmit": (None, 15),
    "Stop": (None, 30),
    "SessionStart": ("compact", 15),
}
EXTRA_RULES = [["rm", "-rf"], ["rm", "-fr"]]  # Codex only: Claude Code asks for these through the hook alone

# config.toml: features.unified_exec_tty is a stable Codex feature (`codex features list`), on by default. Off,
# exec_command refuses tty=true ("TTY execution is disabled by config") and write_stdin can then only poll or
# send Ctrl-C ("stdin is closed for this session"): codex-rs/core/src/tools/handlers/unified_exec/preparation.rs
# and codex-rs/core/src/unified_exec/process_manager.rs. (features.unified_exec itself cannot be turned off by
# a user: codex-rs/core/src/config/managed_features.rs re-enables it.)
MARK = "# agent-playbook"
TTY_LINE = f"unified_exec_tty = false  {MARK}: no interactive terminals, so write_stdin cannot type unchecked commands"
FEATURES_LINE = f"[features]  {MARK}"
BREAK = " (and the line break before this line)"  # we had to end the user's last line first
OUR_LINES = {TTY_LINE, FEATURES_LINE, TTY_LINE + BREAK, FEATURES_LINE + BREAK}
FEATURES_HEADER = re.compile(r"^[ \t]*\[[ \t]*features[ \t]*\][ \t]*(#.*)?$")


def hooks_fragment() -> str:
    hooks = {}
    for event, (matcher, timeout) in EVENTS.items():
        group = {"hooks": [{"type": "command", "command": "{COMMAND}", "timeout": timeout}]}
        if matcher is not None:
            group = {"matcher": matcher, **group}
        hooks[event] = [group]
    return json.dumps({"hooks": hooks}, indent=2) + "\n"


def rules(build) -> str:
    """build.ASK_RULES' shell rules as Codex prefix rules (argv prefix match: the hook stays the main check)."""
    prefixes = [r[len("Bash("):-len(" *)")].split() for r in build.ASK_RULES
                if r.startswith("Bash(") and r.endswith(" *)")] + EXTRA_RULES
    lines = ["# agent-playbook (generated by tools/build.py; reinstalling replaces this file).",
             "# Tier-2 commands (core rule 2.3): Codex asks before running them. Prefix match only;",
             "# the agent-playbook PreToolUse hook is the main check.", ""]
    for words in prefixes:
        command = " ".join(words)
        lines += ["prefix_rule(",
                  f"    pattern = {json.dumps(words)},",
                  '    decision = "prompt",',
                  f"    justification = {json.dumps('agent-playbook rule 2.3: ' + command + ' is tier-2; confirm with the user first')},",
                  f"    match = {json.dumps([command + ' x'])},",
                  ")", ""]
    return "\n".join(lines)


def outputs(build) -> dict[str, str]:
    """dist-relative path ("codex/...") -> content."""
    return {
        "codex/hooks.fragment.json": hooks_fragment(),
        f"codex/rules/{RULES_NAME}": rules(build),
    }


# --- install ---------------------------------------------------------------------

def command(python: str, script: Path) -> str:
    """One string, as Codex runs it: through %COMSPEC% /C on Windows, $SHELL -lc elsewhere."""
    if os.name == "nt":
        return f'"{python}" "{script.as_posix()}" --client codex'
    return f"{shlex.quote(python)} {shlex.quote(script.as_posix())} --client codex"


def agents_block(out: dict[str, str], profiles: list[str]) -> str:
    """The core with the chosen profiles inside its markers, so one block holds everything that is ours."""
    import build
    core = out["global/rules/agent-playbook.md"]
    core = core[len(build.HEADER):] if core.startswith(build.HEADER) else core
    end = core.rindex(CORE_END)
    return core[:end] + "".join("\n" + build.profile(p) for p in profiles) + core[end:]


def load_hooks(text: str | None) -> dict:
    try:
        data = json.loads(text) if text and text.strip() else {}
    except ValueError as exc:
        raise SystemExit(f"hooks.json is not plain JSON ({exc}); nothing was written. Fix it and retry.")
    if not isinstance(data, dict) or not isinstance(data.get("hooks", {}), dict):
        raise SystemExit("hooks.json is not a JSON object with a \"hooks\" object; nothing was written.")
    return data


def without_ours(hooks: dict) -> dict:
    """Every event and group as it was, minus our handlers; groups and events left empty are dropped."""
    import install
    kept_events = {}
    for event, groups in hooks.items():
        if not isinstance(groups, list):
            kept_events[event] = groups
            continue
        kept = []
        for group in groups:
            if not isinstance(group, dict) or not isinstance(group.get("hooks"), list):
                kept.append(group)
                continue
            items = [h for h in group["hooks"] if not (isinstance(h, dict) and install.is_ours(h))]
            if items:
                kept.append({**group, "hooks": items})
        if kept:
            kept_events[event] = kept
    return kept_events


def merge_hooks(existing: str | None, fragment: dict) -> str:
    data = load_hooks(existing)
    hooks = without_ours(data.get("hooks") or {})
    for event, groups in fragment["hooks"].items():
        hooks[event] = hooks.get(event, []) + groups
    return json.dumps({**data, "hooks": hooks}, indent=2, ensure_ascii=False) + "\n"


def unmerge_hooks(existing: str) -> str | None:
    """Our handlers removed. None (remove the file) when nothing at all is left in it."""
    data = load_hooks(existing)
    data["hooks"] = without_ours(data.get("hooks") or {})
    if not data["hooks"] and set(data) == {"hooks"}:
        return None
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def config_with_tty_off(text: str | None) -> tuple[str | None, str | None]:
    """(config.toml with our marked `unified_exec_tty = false`, or None to leave it; a note for the user).
    Only whole lines are added, so removing them gives back the file byte for byte. The result is parsed and
    must equal the original settings plus this one key, or nothing is changed."""
    import tomllib
    text = text or ""
    if any(line.rstrip("\r\n") in OUR_LINES for line in text.splitlines()):
        return None, None  # already there
    try:
        before = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return None, f"config.toml is not valid TOML ({exc}); add `unified_exec_tty = false` under [features] yourself."
    features = before.get("features")
    if isinstance(features, dict) and "unified_exec_tty" in features:
        if features["unified_exec_tty"] is False:
            return None, None
        return None, ("WARNING: your config.toml sets features.unified_exec_tty = true, which lets Codex type into "
                      "open terminals (write_stdin) where no hook checks the commands. Set it to false to close that.")
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines(keepends=True)
    header = next((i for i, l in enumerate(lines) if FEATURES_HEADER.match(l.rstrip("\r\n"))), None)
    if header is not None:
        if lines[header].endswith("\n"):
            lines.insert(header + 1, TTY_LINE + nl)
        else:  # the header is the last line and has no line break
            lines[header:header + 1] = [lines[header], nl + TTY_LINE + BREAK + nl]
        new = "".join(lines)
    elif "features" in before:  # written as features.x = ... or an inline table: not ours to restructure
        return None, "config.toml defines features without a [features] header; add `unified_exec_tty = false` yourself."
    elif not text:
        new = FEATURES_LINE + nl + TTY_LINE + nl
    elif text.endswith("\n"):
        new = text + FEATURES_LINE + nl + TTY_LINE + nl
    else:
        new = text + nl + FEATURES_LINE + BREAK + nl + TTY_LINE + nl
    expected = {**before, "features": {**(features or {}), "unified_exec_tty": False}}
    try:
        if tomllib.loads(new) != expected:
            raise ValueError("settings changed")
    except (tomllib.TOMLDecodeError, ValueError) as exc:
        return None, f"could not add unified_exec_tty = false to config.toml safely ({exc}); add it under [features] yourself."
    return new, None


def config_without_ours(text: str) -> str:
    """config.toml with our marked lines (and a line break we added) taken out; nothing else changes."""
    out: list[str] = []
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\r\n")
        if body in OUR_LINES:
            if body.endswith(BREAK) and out:
                out[-1] = out[-1][:-2] if out[-1].endswith("\r\n") else out[-1][:-1]
            continue
        out.append(line)
    return "".join(out)


_planned_home: Path | None = None  # for notes(), which install.py calls without arguments
_plan_notes: list[str] = []


def plan_global(home: Path, out: dict[str, str], python: str, profiles: list[str]) -> dict[Path, str | None]:
    import install
    global _planned_home
    _planned_home = home
    codex = home / ".codex"
    plan: dict[Path, str | None] = {}
    config = codex / "config.toml"
    if config.exists() and config.read_bytes().startswith(b"\xef\xbb\xbf"):
        new, note = None, "config.toml starts with a byte-order mark; add `unified_exec_tty = false` under [features] yourself."
    else:
        new, note = config_with_tty_off(install.read(config))
    if new is not None:
        plan[config] = new
    _plan_notes[:] = [note] if note else []
    agents = codex / "AGENTS.md"
    current = install.read(agents)
    block = agents_block(out, profiles)
    plan[agents] = block if current is None or not current.strip() else install.merge_block(current, block)
    fragment = json.loads(out["codex/hooks.fragment.json"].replace(
        "{COMMAND}", json.dumps(command(python, codex / HOOK_REL / "playbook_hook.py"))[1:-1]))
    plan[codex / "hooks.json"] = merge_hooks(install.read(codex / "hooks.json"), fragment)
    plan[codex / "rules" / RULES_NAME] = out[f"codex/rules/{RULES_NAME}"]
    for rel, text in out.items():
        if rel.startswith("global/agent-playbook/hooks/"):
            plan[codex / HOOK_REL / rel.rsplit("/", 1)[1]] = text
        elif rel.startswith("global/skills/"):
            plan[home / ".agents" / rel[len("global/"):]] = text
    return plan


def plan_uninstall(home: Path) -> tuple[dict[Path, str | None], list[str]]:
    """Removes our files if unchanged since the install, our hook handlers, and our AGENTS.md block."""
    import build
    import install
    codex = home / ".codex"
    out = build.outputs()
    plan: dict[Path, str | None] = {}
    notes: list[str] = []
    ours = {codex / "rules" / RULES_NAME: out[f"codex/rules/{RULES_NAME}"]}
    for rel, text in out.items():
        if rel.startswith("global/agent-playbook/hooks/"):
            ours[codex / HOOK_REL / rel.rsplit("/", 1)[1]] = text
        elif rel.startswith("global/skills/"):
            ours[home / ".agents" / rel[len("global/"):]] = text
    for path, text in ours.items():
        current = install.read(path)
        if current is None:
            continue
        if current == text:
            plan[path] = None
        else:
            notes.append(f"kept {path}: it changed since the install; remove it yourself if it is ours")
    cache = codex / HOOK_REL / "__pycache__"  # Python's compiled copies of the hook scripts
    for path in sorted(cache.glob("*.pyc")) if cache.is_dir() else []:
        plan[path] = None
    hooks_json = codex / "hooks.json"
    if (current := install.read(hooks_json)) is not None:
        hooks = load_hooks(current).get("hooks") or {}
        if without_ours(hooks) != hooks:
            new = unmerge_hooks(current)
            original = install.oldest_backup(hooks_json)  # the file before the first install, if there was one
            try:
                same = new is not None and original is not None and load_hooks(original) == json.loads(new)
            except SystemExit:
                same = False
            if same:
                new = original  # the same hooks: give back the user's own formatting too
            plan[hooks_json] = new
    agents = codex / "AGENTS.md"
    if (current := install.read(agents)) is not None and install.CORE_BLOCK.search(current):
        rest = install.CORE_BLOCK.sub("", current, count=1)
        original = install.oldest_backup(agents)  # the file before the first install
        if original is not None and original.rstrip() == rest.rstrip():
            plan[agents] = original
        else:
            plan[agents] = rest.rstrip() + "\n" if rest.strip() else None
    config = codex / "config.toml"
    if (current := install.read(config)) is not None:
        new = config_without_ours(current)
        if new != current:  # an empty file we created goes; an empty file that was there before stays
            plan[config] = None if not new and install.oldest_backup(config) is None else new
        elif re.search(r"^\s*unified_exec_tty\s*=\s*false\b", current, re.M):
            notes.append(f"kept `unified_exec_tty = false` in {config}: it has no agent-playbook mark, so it may be "
                         "yours; delete that line yourself if not")
    backups = sorted(p for d in {p.parent for p in plan} if d.exists() for p in d.glob("*.bak-agent-playbook-*"))
    if backups:
        notes.append(f"kept {len(backups)} backup file(s) (*.bak-agent-playbook-*); delete them yourself when sure")
    if (home / ".claude" / "agent-playbook" / "state").exists():
        notes.append(f"kept {home / '.claude' / 'agent-playbook'}: the hook's logs and state, shared with Claude Code")
    return plan, notes


def notes() -> list[str]:
    """Steps the user must do by hand after installing."""
    home = _planned_home or Path.home()
    codex = home / ".codex"
    lines = [
        "Next, in Codex:",
        "  1. Start the Codex CLI and type /hooks. Review the 5 agent-playbook hooks and trust them. Codex skips",
        "     a hook until you trust it, and asks again whenever its entry in hooks.json changes (for example",
        "     after an update that changes the Python path); trust them again then. Until then, Codex warns at",
        "     startup that hooks need review.",
        "  2. Start a new session so Codex loads the new AGENTS.md block and the skills.",
        "  3. Codex hooks cannot show an approval prompt. When agent-playbook stops a tier-2 action, Codex",
        "     will ask you in the chat with a 4-character code; reply \"approve CODE\" (or \"批准 CODE\") to let",
        "     that exact action run once. Any other reply approves nothing.",
        "  These are user-level hooks, so they run in every project. Hooks in a project's own .codex/ folder",
        "  run only after you trust that project.",
    ]
    lines += _plan_notes or [  # a note means config.toml was left as it is
        "  Codex no longer opens interactive terminals (unified_exec_tty = false in config.toml): commands",
        "  still run and can be stopped, but a program that waits for typed input will not get any."]
    if (codex / "AGENTS.override.md").exists() and (codex / "AGENTS.override.md").read_text(
            encoding="utf-8", errors="replace").strip():
        lines.append(f"WARNING: {codex / 'AGENTS.override.md'} exists, so Codex ignores AGENTS.md and the rules "
                     "in it. Move your text from AGENTS.override.md into AGENTS.md, or delete the override.")
    if os.environ.get("CODEX_HOME") and Path(os.environ["CODEX_HOME"]).resolve() != codex.resolve():
        lines.append(f"WARNING: CODEX_HOME is set to {os.environ['CODEX_HOME']}, but this installed into {codex}. "
                     "Codex reads only CODEX_HOME.")
    config = codex / "config.toml"
    if config.exists() and re.search(r"^\s*\[\[?hooks[.\]]", config.read_text(encoding="utf-8", errors="replace"), re.M):
        lines.append(f"Note: {config} also defines hooks; Codex loads both and warns at startup.")
    return lines
