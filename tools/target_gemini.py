"""Install target for Gemini CLI: one extension folder, one user policy file, one settings key.

~/.gemini/extensions/agent-playbook/        Gemini CLI loads every folder here at start
  gemini-extension.json                     name, version, contextFileName (docs/extensions/reference.md)
  GEMINI.md                                 core rules + the chosen profiles, always in context
  hooks/hooks.json                          BeforeTool, AfterTool, BeforeAgent, AfterAgent -> playbook_hook.py
  hooks/*.py                                the hook scripts, the same files as the Claude Code install
  skills/<name>/SKILL.md                    pb-rehearse, pb-status, pb-handoff, lessons
  installed.json                            version, profiles, and what the install added to settings.json
~/.gemini/policies/agent-playbook.toml      ask_user for the tier-2 command families: a second layer that
                                            still asks when the hook crashes or times out (it fails open)
~/.gemini/settings.json                     context.fileName gains AGENTS.md and GEMINI.md, so a project's
                                            AGENTS.md (the project install) is read too; other keys are kept

dist/gemini/ holds these files, except the hook scripts (taken from dist/global/), hooks.json (its
template, hooks.template.json, gets this machine's Python at install) and installed.json.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import sys
from pathlib import Path

NAME = "agent-playbook"
DIST_EXT = f"gemini/extensions/{NAME}/"
DIST_HOOKS = "gemini/hooks.template.json"
DIST_POLICY = "gemini/policies/agent-playbook.toml"
PYTHON = "{PYTHON}"  # filled in at install with this machine's Python
SCRIPT = '"${extensionPath}${/}hooks${/}playbook_hook.py" --client gemini'  # Gemini fills ${...} at load
CONTEXT_FILES = ("AGENTS.md", "GEMINI.md")
_plan_notes: list[str] = []  # notes found while planning, shown by notes()


def extension_dir(home: Path) -> Path:
    return home / ".gemini" / "extensions" / NAME


def policy_file(home: Path) -> Path:
    return home / ".gemini" / "policies" / "agent-playbook.toml"


def settings_file(home: Path) -> Path:
    return home / ".gemini" / "settings.json"


def record_file(home: Path) -> Path:
    return extension_dir(home) / "installed.json"


# --- build ---------------------------------------------------------------------------------------


def client(build):
    """src/hooks/client_gemini.py: its matcher list is the one source for which tools change state."""
    import importlib  # noqa: PLC0415
    hooks = str(build.SRC / "hooks")
    if hooks not in sys.path:
        sys.path.insert(0, hooks)
    return importlib.import_module("client_gemini")


def hooks_template(build) -> str:
    """Gemini hooks (docs/hooks/reference.md). Timeouts are in milliseconds. A hook that times out lets
    the call through, so BeforeTool keeps Gemini's full default of 60 s rather than a short limit."""
    def entry(event, timeout, matcher=None):
        group = {"hooks": [{"name": f"{NAME}-{event}", "type": "command", "command": f"{PYTHON} {SCRIPT}",
                            "timeout": timeout, "description": "agent-playbook policy hook"}]}
        return [{"matcher": matcher, **group} if matcher is not None else group]

    hooks = {"hooks": {
        "BeforeTool": entry("before-tool", 60000, "*"),
        "AfterTool": entry("after-tool", 30000, client(build).AFTER_TOOL_MATCHER),
        "BeforeAgent": entry("before-agent", 30000),
        "AfterAgent": entry("after-agent", 30000),
    }}
    return json.dumps(hooks, indent=2) + "\n"


def policy_toml(ask_rules: list[str]) -> str:
    """The Claude Code ask rules (build.ASK_RULES) as Gemini policy rules (docs/reference/policy-engine.md)."""
    prefixes = [r[len("Bash("):-len(" *)")] for r in ask_rules if r.startswith("Bash(") and r.endswith(" *)")]
    prefixes += [f"gemini extensions {verb}" for verb in  # turning the playbook itself off (rule 2.3)
                 ("install", "uninstall", "update", "enable", "disable", "link", "config")]
    servers: dict[str, list[str]] = {}
    for rule in ask_rules:
        parts = rule.split("__")
        if rule.startswith("mcp__") and len(parts) == 3:
            servers.setdefault(parts[1], []).append(parts[2])
    q = json.dumps  # a JSON string of ASCII text is a valid TOML basic string
    lines = ["# agent-playbook: tier-2 command families ask before they run (core rule 2.3).",
             "# A second layer under the BeforeTool hook, which lets a call through if it crashes or times out.",
             "# Generated by tools/build.py from src/; do not edit. Priority 999 in the user tier (4.999) ranks",
             "# above Gemini's \"Always allow\" choices (4.95), so those cannot skip these questions.", "",
             "[[rule]]", 'toolName = "run_shell_command"',
             "commandPrefix = [" + ", ".join(q(p) for p in prefixes) + "]",
             'decision = "ask_user"', "priority = 999"]
    for server, tools in servers.items():
        lines += ["", "[[rule]]", f"mcpName = {q(server)}", "toolName = [" + ", ".join(q(t) for t in tools) + "]",
                  'decision = "ask_user"', "priority = 999"]
    return "\n".join(lines) + "\n"


def outputs(build) -> dict[str, str]:
    """dist-relative path ("gemini/...") -> content."""
    manifest = {"name": NAME, "version": build.VERSION,
                "description": "agent-playbook: working rules, tier-2 approval and the end-of-turn report check",
                "contextFileName": "GEMINI.md"}
    out = {
        DIST_EXT + "gemini-extension.json": json.dumps(manifest, indent=2) + "\n",
        DIST_EXT + "GEMINI.md": build.HEADER + build.core(),
        DIST_HOOKS: hooks_template(build),
        DIST_POLICY: policy_toml(build.ASK_RULES),
    }
    for name, text in build.skills().items():
        out[f"{DIST_EXT}skills/{name}/SKILL.md"] = text
    return out


# --- install ---------------------------------------------------------------------------------------


def hook_command(python: str, windows: bool | None = None) -> str:
    """Gemini runs a hook command through PowerShell on Windows (and appends `; if ($LASTEXITCODE ...)`),
    through bash elsewhere (packages/core/src/hooks/hookRunner.ts). A quoted program needs `&` in PowerShell."""
    windows = os.name == "nt" if windows is None else windows
    exe = "& '" + python.replace("'", "''") + "'" if windows else shlex.quote(python)
    return f"{exe} {SCRIPT}"


def hooks_json(template: str, python: str, windows: bool | None = None) -> str:
    data = json.loads(template)
    for groups in data["hooks"].values():
        for group in groups:
            for hook in group["hooks"]:
                hook["command"] = hook["command"].replace(f"{PYTHON} {SCRIPT}", hook_command(python, windows))
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _read(path: Path) -> str | None:
    import install  # noqa: PLC0415 - install imports build, which imports this module
    return install.read(path)


def _record(home: Path) -> dict:
    try:
        data = json.loads(_read(record_file(home)) or "{}")
    except ValueError:
        return {}
    return data if isinstance(data, dict) else {}


def _names(value) -> list[str]:
    return [value] if isinstance(value, str) else [v for v in value if isinstance(v, str)] \
        if isinstance(value, list) else []


def merge_settings(existing: str | None) -> tuple[str | None, list[str]]:
    """(settings.json with AGENTS.md and GEMINI.md in context.fileName, the names it added).
    Every other key is kept; a file that needs nothing is returned exactly as it was."""
    try:
        data = json.loads(existing) if existing and existing.strip() else {}
    except ValueError:
        data = None
    if not isinstance(data, dict) or not isinstance(data.get("context", {}), dict):
        _plan_notes.append("~/.gemini/settings.json is not plain JSON (comments?) or has an unexpected shape, so it "
                           'was left alone. For Gemini to read AGENTS.md too, add "context": {"fileName": '
                           '["AGENTS.md", "GEMINI.md"]} to it yourself.')
        return existing, []
    context = data.setdefault("context", {})
    names = _names(context.get("fileName"))
    missing = [n for n in CONTEXT_FILES if n not in names]
    if not missing:
        return existing, []
    context["fileName"] = names + missing
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n", missing


def unmerge_settings(existing: str | None, record: dict) -> str | None:
    """Take out the context file names the install added (record["added"]); restore the old value
    when nothing else changed. None: the install created the file and it is now empty."""
    try:
        data = json.loads(existing) if existing and existing.strip() else None
    except ValueError:
        return existing
    added = _names(record.get("added"))
    if not isinstance(data, dict) or not isinstance(data.get("context"), dict) or not added:
        return existing
    names = _names(data["context"].get("fileName"))
    kept = [n for n in names if n not in added]
    before = record.get("before")
    if before is not None and kept == _names(before):
        data["context"]["fileName"] = before  # the user's own value, string or list, as it was
    elif kept:
        data["context"]["fileName"] = kept
    else:
        data["context"].pop("fileName", None)
    if not data["context"]:
        del data["context"]
    if not data and record.get("created"):
        return None
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def plan_global(home: Path, out: dict[str, str], python: str, profiles: list[str]) -> dict[Path, str | None]:
    import build  # noqa: PLC0415
    _plan_notes.clear()
    ext = extension_dir(home)
    plan: dict[Path, str | None] = {}
    for rel, text in out.items():
        if rel.startswith(DIST_EXT):
            if rel == DIST_EXT + "GEMINI.md":
                text += "".join("\n" + build.profile(p) for p in profiles)
            plan[ext / rel[len(DIST_EXT):]] = text
        elif rel.startswith(f"global/{NAME}/hooks/"):
            plan[ext / "hooks" / rel.rsplit("/", 1)[1]] = text
    plan[ext / "hooks" / "hooks.json"] = hooks_json(out[DIST_HOOKS], python)
    plan[policy_file(home)] = out[DIST_POLICY]
    settings = settings_file(home)
    current = _read(settings)
    merged, added = merge_settings(current)
    if merged != current:
        plan[settings] = merged
    # What the install added to settings.json, kept across updates, so uninstall takes out only that.
    old = _record(home).get("settings")
    old = old if isinstance(old, dict) else None
    before = None
    if current is not None and not _plan_notes:
        ctx = json.loads(current).get("context") if current.strip() else None
        before = ctx.get("fileName") if isinstance(ctx, dict) else None
    record = {"added": [n for n in CONTEXT_FILES if n in _names(old["added"]) + added] if old else added,
              "before": old["before"] if old else before,
              "created": old["created"] if old else current is None}
    plan[record_file(home)] = json.dumps({"version": build.VERSION, "profiles": profiles, "settings": record},
                                         indent=1, ensure_ascii=False) + "\n"
    return plan


def is_our_hooks(text: str | None) -> bool:
    """hooks.json as the install wrote it: every hook runs our playbook_hook.py --client gemini."""
    try:
        data = json.loads(text or "")
        commands = [h["command"] for groups in data["hooks"].values() for g in groups for h in g["hooks"]]
    except (ValueError, KeyError, TypeError, AttributeError):
        return False
    return bool(commands) and all(isinstance(c, str) and c.endswith(SCRIPT) for c in commands)


def plan_uninstall(home: Path) -> tuple[dict[Path, str | None], list[str]]:
    """Remove what the install wrote, if unchanged since; take out what it added to settings.json."""
    import build  # noqa: PLC0415
    out = build.outputs()
    ext = extension_dir(home)
    plan: dict[Path, str | None] = {}
    notes: list[str] = []
    expected = {ext / rel[len(DIST_EXT):]: text for rel, text in out.items() if rel.startswith(DIST_EXT)}
    expected |= {ext / "hooks" / rel.rsplit("/", 1)[1]: text for rel, text in out.items()
                 if rel.startswith(f"global/{NAME}/hooks/")}
    expected[policy_file(home)] = out[DIST_POLICY]
    for path, text in expected.items():
        current = _read(path)
        if current is None:
            continue
        # GEMINI.md has the chosen profiles after the core, so only its start is compared
        if current.startswith(text) if path == ext / "GEMINI.md" else current == text:
            plan[path] = None
        else:
            notes.append(f"kept {path}: it changed since the install; remove it yourself if it is ours")
    hooks = ext / "hooks" / "hooks.json"
    if (current := _read(hooks)) is not None:
        if is_our_hooks(current):
            plan[hooks] = None
        else:
            notes.append(f"kept {hooks}: it changed since the install; remove it yourself if it is ours")
    record = _record(home).get("settings")
    settings = settings_file(home)
    if (current := _read(settings)) is not None:
        if isinstance(record, dict):
            new = unmerge_settings(current, record)
            if new != current:
                plan[settings] = new
        else:
            notes.append(f"kept {settings} as it is: no install record says what was added to it")
    if record_file(home).exists():
        plan[record_file(home)] = None
    leftovers = sorted(p for p in ext.rglob("*") if p.is_file() and p not in plan) if ext.exists() else []
    if leftovers:
        notes.append(f"kept {len(leftovers)} other file(s) in {ext}; delete the folder yourself when sure")
    notes.append(f"kept {home / '.claude' / 'agent-playbook'} (logs, state), which the Gemini hooks share")
    return plan, notes


def installed_profiles(home: Path) -> list[str] | None:
    """The optional profiles of the last Gemini install, so an update can keep them; None if never installed."""
    import build  # noqa: PLC0415
    profiles = _record(home).get("profiles")
    return [p for p in profiles if p in build.PUBLIC_PROFILES] if isinstance(profiles, list) else None


